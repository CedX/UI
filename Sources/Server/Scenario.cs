	/// </summary>
	public const string Delete = "Delete";

	/// <summary>
	/// A scenario in which the underlying model is read.
	/// </summary>
	public const string Read = "Read";

	/// <summary>
	/// A scenario in which the underlying model is updated.
	/// </summary>
	public const string Update = "Update";
}
